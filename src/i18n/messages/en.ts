/**
 * `as const` gives us exact keys for `MessageKey`, but it would also pin every
 * VALUE to its English literal — making a translation a type error. Widen the
 * leaves back to `string` while keeping the key structure intact.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

export type Messages = Widen<typeof en>;
